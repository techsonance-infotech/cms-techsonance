import fs from 'fs';
import path from 'path';

export function toOpenApiPath(filePath) {
  const normalized = filePath.replace(/\\/g, '/');
  const match = normalized.match(/\/src\/app(\/api\/.*)\/route\.(ts|js|tsx|jsx)/);
  if (!match) return '';
  return match[1].replace(/\[([^\]]+)\]/g, '{$1}');
}

export function inferTag(openApiPath) {
  const segments = openApiPath.split('/').filter(Boolean);
  if (segments[0] === 'api' && segments[1]) {
    return segments[1];
  }
  return 'default';
}

export function createSpec() {
  const spec = {
    openapi: '3.0.3',
    info: {
      title: 'Enterprise Business Management Platform API',
      version: '1.0.0',
      description: 'Swagger API documentation generated by AST router parser.'
    },
    paths: {}
  };

  const apiDir = path.join(process.cwd(), 'src', 'app', 'api');
  
  function scanDir(dir) {
    if (!fs.existsSync(dir)) return;
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        scanDir(fullPath);
      } else if (entry.isFile() && (entry.name === 'route.ts' || entry.name === 'route.js')) {
        const apiPath = toOpenApiPath(fullPath);
        if (!apiPath) continue;

        const tag = inferTag(apiPath);
        const fileContent = fs.readFileSync(fullPath, 'utf8');
        
        const methods = ['GET', 'POST', 'PUT', 'DELETE', 'PATCH'];
        const pathItem = {};

        for (const method of methods) {
          if (fileContent.includes(`export const ${method}`) || fileContent.includes(`export async function ${method}`)) {
            pathItem[method.toLowerCase()] = {
              tags: [tag],
              summary: `${method} handler for ${apiPath}`,
              responses: {
                200: {
                  description: 'Successful request execution.'
                }
              }
            };
          }
        }

        if (Object.keys(pathItem).length > 0) {
          spec.paths[apiPath] = pathItem;
        }
      }
    }
  }

  scanDir(apiDir);
  return spec;
}

export function writeSpecFiles() {
  const spec = createSpec();
  const docsDir = path.join(process.cwd(), 'public', 'docs');
  if (!fs.existsSync(docsDir)) {
    fs.mkdirSync(docsDir, { recursive: true });
  }
  fs.writeFileSync(path.join(docsDir, 'swagger.json'), JSON.stringify(spec, null, 2));
  
  let yaml = `openapi: 3.0.3\ninfo:\n  title: ${spec.info.title}\n  version: ${spec.info.version}\n  description: ${spec.info.description}\npaths:\n`;
  for (const [apiPath, pathObj] of Object.entries(spec.paths)) {
    yaml += `  "${apiPath}":\n`;
    for (const [method, methodObj] of Object.entries(pathObj)) {
      yaml += `    ${method}:\n      tags:\n        - ${methodObj.tags[0]}\n      summary: "${methodObj.summary}"\n      responses:\n        200:\n          description: "Successful request execution."\n`;
    }
  }
  fs.writeFileSync(path.join(docsDir, 'swagger.yaml'), yaml);
}

// Support running directly in CLI
if (import.meta.url.endsWith(process.argv[1])) {
  writeSpecFiles();
}

-- Enable pgcrypto if not already enabled (usually done in bootstrap, but safe to repeat)
create extension if not exists pgcrypto;

-- Alter existing employees table to add HR and Financial fields
DO $$ 
BEGIN 
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='employees' AND column_name='employment_type') THEN
    ALTER TABLE public.employees 
      ADD COLUMN employment_type text default 'full_time',
      ADD COLUMN hourly_rate numeric(15,4),
      ADD COLUMN ctc numeric(15,4),
      ADD COLUMN pf_number text,
      ADD COLUMN uan_number text,
      ADD COLUMN bank_name text,
      ADD COLUMN bank_account_number text,
      ADD COLUMN ifsc_code text,
      ADD COLUMN manager_id uuid REFERENCES public.users(id) ON DELETE SET NULL;
  END IF;
END $$;

-- Create Employee Documents Table (Document Vault)
CREATE TABLE IF NOT EXISTS public.employee_documents (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  employee_id bigint not null references public.employees(id) on delete cascade,
  document_type text not null, -- e.g., 'resume', 'offer_letter', 'id_proof', 'other'
  name text not null,
  file_url text not null,
  uploaded_by uuid not null references public.users(id) on delete restrict,
  uploaded_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Enable RLS
ALTER TABLE public.employee_documents ENABLE ROW LEVEL SECURITY;

-- Recreate/Add Document Vault to tenant configuration if applicable
-- For the Vault, we just need basic RLS policies if it's following the multi-tenant pattern
-- The generalized RBAC policies typically handle tables. We add it here to be safe:
CREATE POLICY "Enable read access for users in same tenant" 
  ON public.employee_documents FOR SELECT 
  USING (tenant_id = (select auth.jwt() ->> 'tenant_id')::uuid);

CREATE POLICY "Enable insert for users in same tenant" 
  ON public.employee_documents FOR INSERT 
  WITH CHECK (tenant_id = (select auth.jwt() ->> 'tenant_id')::uuid);

CREATE POLICY "Enable update for users in same tenant" 
  ON public.employee_documents FOR UPDATE 
  USING (tenant_id = (select auth.jwt() ->> 'tenant_id')::uuid);

CREATE POLICY "Enable delete for users in same tenant" 
  ON public.employee_documents FOR DELETE 
  USING (tenant_id = (select auth.jwt() ->> 'tenant_id')::uuid);

-- Trigger for updated_at
create or replace function public.handle_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists set_updated_at on public.employee_documents;
create trigger set_updated_at
  before update on public.employee_documents
  for each row
  execute function public.handle_updated_at();
